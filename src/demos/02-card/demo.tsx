import { VectorUIRoot } from "../../components/VectorUIRoot";
import { Flow } from "../../components/Flow";
import { Card } from "./Card";
import { LandscapeCard } from "./LandscapeCard";

/**
 * Demo 2 — non-rectangular card (SPEC §11).
 *
 * Two cards, each a `Frame` with named slots — but different shapes. Version
 * A's outline carves a scoop into the left edge and the body text follows it;
 * version B is a hand-drawn postcard with a wobbly rectangular outline and a
 * mountain-silhouette horizon between title and body.
 *
 * Proves: `Frame`, the slot system, path-as-container, flow-around — and that
 * "the path is the container" supports more than one card design.
 */

const BODY_A =
  "The card's left edge is not straight: a smooth scoop is carved out of it, and this paragraph is poured to follow that exact curve. The lines step inward as the scoop deepens, then square off below it. The very same function generates the drawn outline and the wrap profile, so the text hugs the contour that is rendered — not an approximation of it. Hover the card and the scoop deepens; the four edges also pick up a hand-drawn wobble, and the text re-flows around the new shape as it animates.";

const BODY_B =
  "The dark triangle to the left is the title's frame, and the wobbly slope of its right side dictates exactly how far this paragraph indents on each line. The first lines hug the peak closely, then step further inward as the slope flares to the base — every bend of the hand-drawn contour pushes a line by precisely that amount. Below the triangle the column squares back off to the card's full width. The path and the wrap profile are generated by the same function, so the text follows the rendered contour rather than an approximation of it. The four outer edges of the card carry their own (gentler) wobble — this whole postcard is one SVG, no <img>, no <hr>, no <div>.";

const ROOT_WIDTH = 520;
const MARGIN = 56;

export function Demo() {
  return (
    <div>
      <p style={{ color: "#555", maxWidth: 640 }}>
        Two cards, each a generated path. <strong>Version A</strong> carves a
        scoop into its left edge and pours the body around it — hover to deepen
        the scoop and wobble all four edges. <strong>Version B</strong> is a
        hand-drawn postcard whose title sits inside a triangle, with the body
        text wrapping the triangle's wobbly right slope.
      </p>

      <p className="variant-label">
        Version A — scoop edge, hover wobbles all four sides
      </p>
      <VectorUIRoot
        width={ROOT_WIDTH}
        height="content"
        style={{ maxWidth: ROOT_WIDTH, background: "#f0efe9" }}
      >
        <Flow padding={MARGIN} align="center" crossSize={ROOT_WIDTH - MARGIN * 2}>
          <Card
            width={400}
            scoopDepth={104}
            title="Text follows the path"
            body={BODY_A}
            actionLabel="Got it"
          />
        </Flow>
      </VectorUIRoot>

      <p className="variant-label">
        Version B — hand-drawn postcard, title in a triangle, body wraps its slope
      </p>
      <VectorUIRoot
        width={ROOT_WIDTH}
        height="content"
        style={{ maxWidth: ROOT_WIDTH, background: "#e8e3d3" }}
      >
        <Flow padding={MARGIN} align="center" crossSize={ROOT_WIDTH - MARGIN * 2}>
          <LandscapeCard
            width={400}
            title="A spooky wobbly title that follows the path"
            body={BODY_B}
          />
        </Flow>
      </VectorUIRoot>
    </div>
  );
}
